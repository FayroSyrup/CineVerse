-- Core tables: users and the main lookup tables.

CREATE TABLE users (
  user_id        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  name           VARCHAR2(255) NOT NULL,
  email          VARCHAR2(320) NOT NULL,
  password_hash  VARCHAR2(255) NOT NULL,  -- bcrypt hash, never plain text
  gender         VARCHAR2(10),
  role           VARCHAR2(10) DEFAULT 'USER' NOT NULL,
  join_date      DATE DEFAULT SYSDATE NOT NULL,
  image_url      VARCHAR2(500),
  CONSTRAINT pk_users PRIMARY KEY (user_id),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT ck_users_role CHECK (role IN ('ADMIN','USER'))
);

CREATE TABLE production_house (
  production_house_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  name         VARCHAR2(255) NOT NULL,
  found_date   DATE,
  description  CLOB,
  website_url  VARCHAR2(500),
  image_url    VARCHAR2(500),
  CONSTRAINT pk_production_house PRIMARY KEY (production_house_id)
);

CREATE TABLE directors (
  director_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  name           VARCHAR2(255) NOT NULL,
  date_of_birth  DATE,
  biography      CLOB,
  gender         VARCHAR2(10),
  debut_year     DATE,
  image_url      VARCHAR2(500),
  CONSTRAINT pk_directors PRIMARY KEY (director_id)
);

CREATE TABLE actors (
  actor_id       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  name           VARCHAR2(255) NOT NULL,
  date_of_birth  DATE,
  biography      CLOB,
  gender         VARCHAR2(10),
  debut_year     DATE,
  image_url      VARCHAR2(500),
  CONSTRAINT pk_actors PRIMARY KEY (actor_id)
);

CREATE TABLE genres (
  genre_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  name         VARCHAR2(100) NOT NULL,
  description  CLOB,
  CONSTRAINT pk_genres PRIMARY KEY (genre_id),
  CONSTRAINT uq_genres_name UNIQUE (name)
);

CREATE TABLE awards (
  award_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  name        VARCHAR2(255) NOT NULL,
  award_year  NUMBER(4),
  category    VARCHAR2(100),
  image_url   VARCHAR2(500),
  CONSTRAINT pk_awards PRIMARY KEY (award_id)
);

CREATE TABLE streaming_platforms (
  platform_id  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  name         VARCHAR2(255) NOT NULL,
  website_url  VARCHAR2(500),
  image_url    VARCHAR2(500),
  CONSTRAINT pk_streaming_platforms PRIMARY KEY (platform_id),
  CONSTRAINT uq_platform_name UNIQUE (name)
);

CREATE TABLE fan_communities (
  community_id   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  platform       VARCHAR2(255),
  creation_date  DATE,
  total_members  NUMBER(10) DEFAULT 0 NOT NULL,  -- kept up to date by a trigger later
  CONSTRAINT pk_fan_communities PRIMARY KEY (community_id)
);