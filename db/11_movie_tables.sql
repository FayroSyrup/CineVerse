-- Movies and tables that link to movies.

CREATE TABLE movies (
  movie_id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  title                VARCHAR2(255) NOT NULL,
  director_id          NUMBER(10),
  production_house_id  NUMBER(10),
  release_date         DATE,
  duration_min         NUMBER(4),
  language             VARCHAR2(50),
  description          CLOB,
  subtitle             VARCHAR2(500),
  image_url            VARCHAR2(500),
  avg_rating           NUMBER(3,1) DEFAULT 0 NOT NULL,  -- kept up to date by a trigger later
  rating_count         NUMBER(10) DEFAULT 0 NOT NULL,   -- kept up to date by a trigger later
  CONSTRAINT pk_movies PRIMARY KEY (movie_id),
  CONSTRAINT fk_movies_director FOREIGN KEY (director_id)
    REFERENCES directors (director_id) ON DELETE SET NULL,
  CONSTRAINT fk_movies_house FOREIGN KEY (production_house_id)
    REFERENCES production_house (production_house_id) ON DELETE SET NULL
);

CREATE TABLE movie_cast (
  cast_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  movie_id   NUMBER(10) NOT NULL,
  actor_id   NUMBER(10) NOT NULL,
  cast_name  VARCHAR2(255),
  role       VARCHAR2(255),
  CONSTRAINT pk_movie_cast PRIMARY KEY (cast_id),
  CONSTRAINT uq_movie_cast UNIQUE (movie_id, actor_id),
  CONSTRAINT fk_cast_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE,
  CONSTRAINT fk_cast_actor FOREIGN KEY (actor_id)
    REFERENCES actors (actor_id) ON DELETE CASCADE
);

CREATE TABLE movies_genres (
  movie_id  NUMBER(10) NOT NULL,
  genre_id  NUMBER(10) NOT NULL,
  CONSTRAINT pk_movies_genres PRIMARY KEY (movie_id, genre_id),
  CONSTRAINT fk_mg_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE,
  CONSTRAINT fk_mg_genre FOREIGN KEY (genre_id)
    REFERENCES genres (genre_id) ON DELETE CASCADE
);

CREATE TABLE movies_awards (
  movie_id  NUMBER(10) NOT NULL,
  award_id  NUMBER(10) NOT NULL,
  CONSTRAINT pk_movies_awards PRIMARY KEY (movie_id, award_id),
  CONSTRAINT fk_ma_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE,
  CONSTRAINT fk_ma_award FOREIGN KEY (award_id)
    REFERENCES awards (award_id) ON DELETE CASCADE
);

CREATE TABLE movies_streaming_platforms (
  movie_id     NUMBER(10) NOT NULL,
  platform_id  NUMBER(10) NOT NULL,
  CONSTRAINT pk_movies_platforms PRIMARY KEY (movie_id, platform_id),
  CONSTRAINT fk_msp_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE,
  CONSTRAINT fk_msp_platform FOREIGN KEY (platform_id)
    REFERENCES streaming_platforms (platform_id) ON DELETE CASCADE
);

CREATE TABLE movies_fan_communities (
  movie_id      NUMBER(10) NOT NULL,
  community_id  NUMBER(10) NOT NULL,
  CONSTRAINT pk_movies_communities PRIMARY KEY (movie_id, community_id),
  CONSTRAINT fk_mfc_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE,
  CONSTRAINT fk_mfc_community FOREIGN KEY (community_id)
    REFERENCES fan_communities (community_id) ON DELETE CASCADE
);