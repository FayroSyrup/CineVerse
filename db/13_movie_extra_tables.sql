-- Extra movie details: trailers, promotions, earnings.

CREATE TABLE movie_trailers (
  trailer_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  movie_id      NUMBER(10) NOT NULL,
  release_date  DATE,
  description   CLOB,
  video_url     VARCHAR2(500),
  image_url     VARCHAR2(500),
  CONSTRAINT pk_movie_trailers PRIMARY KEY (trailer_id),
  CONSTRAINT fk_trailer_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE
);

CREATE TABLE movie_promotions (
  promotion_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  movie_id        NUMBER(10) NOT NULL,
  promotion_type  VARCHAR2(255),
  start_date      DATE,
  end_date        DATE,
  budget          NUMBER(15,2),
  CONSTRAINT pk_movie_promotions PRIMARY KEY (promotion_id),
  CONSTRAINT ck_promo_dates CHECK (end_date IS NULL OR end_date >= start_date),
  CONSTRAINT fk_promo_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE
);

CREATE TABLE movie_earnings (
  earning_id           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  movie_id             NUMBER(10) NOT NULL,
  budget               NUMBER(15,2),
  stream_earning       NUMBER(15,2) DEFAULT 0 NOT NULL,
  box_office_earning   NUMBER(15,2) DEFAULT 0 NOT NULL,
  total_earning        NUMBER(15,2) DEFAULT 0 NOT NULL,
  CONSTRAINT pk_movie_earnings PRIMARY KEY (earning_id),
  CONSTRAINT uq_earnings_movie UNIQUE (movie_id),
  CONSTRAINT fk_earn_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE
);