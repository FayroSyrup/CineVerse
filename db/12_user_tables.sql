-- Tables for what users do: rate, review, save, subscribe, join communities.

CREATE TABLE ratings (
  rating_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  movie_id      NUMBER(10) NOT NULL,
  user_id       NUMBER(10) NOT NULL,
  rating_value  NUMBER(3,1) NOT NULL,
  rating_date   DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_ratings PRIMARY KEY (rating_id),
  CONSTRAINT uq_ratings_user_movie UNIQUE (movie_id, user_id),
  CONSTRAINT ck_ratings_value CHECK (rating_value BETWEEN 0 AND 10),
  CONSTRAINT fk_ratings_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE,
  CONSTRAINT fk_ratings_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE TABLE reviews (
  review_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  movie_id     NUMBER(10) NOT NULL,
  user_id      NUMBER(10) NOT NULL,
  review_text  CLOB,
  likes        NUMBER(10) DEFAULT 0 NOT NULL,
  review_date  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_reviews PRIMARY KEY (review_id),
  CONSTRAINT fk_reviews_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE,
  CONSTRAINT fk_reviews_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE TABLE watch_lists (
  watch_list_id  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  user_id        NUMBER(10) NOT NULL,
  movie_id       NUMBER(10) NOT NULL,
  added_date     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_watch_lists PRIMARY KEY (watch_list_id),
  CONSTRAINT uq_watch_lists UNIQUE (user_id, movie_id),
  CONSTRAINT fk_wl_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT fk_wl_movie FOREIGN KEY (movie_id)
    REFERENCES movies (movie_id) ON DELETE CASCADE
);

CREATE TABLE user_subscriptions (
  subscription_id  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  user_id          NUMBER(10) NOT NULL,
  platform_id      NUMBER(10) NOT NULL,
  plan_name        VARCHAR2(255),
  start_date       DATE,
  end_date         DATE,
  CONSTRAINT pk_user_subscriptions PRIMARY KEY (subscription_id),
  CONSTRAINT ck_sub_dates CHECK (end_date IS NULL OR end_date >= start_date),
  CONSTRAINT fk_sub_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT fk_sub_platform FOREIGN KEY (platform_id)
    REFERENCES streaming_platforms (platform_id) ON DELETE CASCADE
);

CREATE TABLE user_fan_communities (
  user_id       NUMBER(10) NOT NULL,
  community_id  NUMBER(10) NOT NULL,
  CONSTRAINT pk_user_communities PRIMARY KEY (user_id, community_id),
  CONSTRAINT fk_ufc_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT fk_ufc_community FOREIGN KEY (community_id)
    REFERENCES fan_communities (community_id) ON DELETE CASCADE
);